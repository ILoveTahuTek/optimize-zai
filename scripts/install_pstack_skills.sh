#!/usr/bin/env bash
# Install Lauren Tan's pstack skills (github.com/cursor/plugins/tree/main/pstack)
# into this sandbox as cursor-<name>, with internal cross-references rewritten
# so the renamed skills can still call each other.
#
# - Never overwrites non-cursor skills; cursor-<name> targets are updated in place.
# - Writes scripts/manifest_cursor_skills.txt (installed names + upstream commit).
#
# Usage: bash scripts/install_pstack_skills.sh
set -euo pipefail

SRC=/tmp/cursor-plugins
PSRC="$SRC/pstack/skills"
DEST=/home/z/my-project/skills
MANIFEST=/home/z/my-project/scripts/manifest_cursor_skills.txt
TRANSFORM=/home/z/my-project/scripts/transform_pstack_refs.py

rm -rf "$SRC"
git clone --depth 1 -q https://github.com/cursor/plugins.git "$SRC"
UPSTREAM=$(git -C "$SRC" log -1 --format='%h %ad' --date=short)
echo "upstream: cursor/plugins $UPSTREAM"

# collision guard: refuse if a cursor- name would clash with an unrelated install
for n in $(ls "$PSRC"); do
  if [ -e "$DEST/cursor-$n" ] && ! grep -qxF "cursor-$n" "$MANIFEST" 2>/dev/null; then
    echo "ABORT: $DEST/cursor-$n already exists but is not from a previous pstack install" >&2
    exit 3
  fi
done

ls "$PSRC" > /tmp/pstack_names.txt
new=0; updated=0; same=0
for n in $(ls "$PSRC"); do
  src="$PSRC/$n"
  target="$DEST/cursor-$n"
  if [ -d "$target" ]; then
    if diff -rq "$src" "$target" >/dev/null 2>&1; then
      same=$((same+1)); echo "SAME      cursor-$n"; continue
    fi
    rsync -a --delete "$src/" "$target/"
    updated=$((updated+1)); echo "UPDATED   cursor-$n"
  else
    rsync -a "$src/" "$target/"
    new=$((new+1)); echo "NEW       cursor-$n"
  fi
  python3 "$TRANSFORM" "$target" /tmp/pstack_names.txt
done

{
  echo "# pstack -> cursor-* install manifest (generated by install_pstack_skills.sh)"
  echo "# upstream: cursor/plugins $UPSTREAM"
  ls "$PSRC" | sed 's/^/cursor-/'
} > "$MANIFEST"
echo "summary: new=$new updated=$updated same=$same (total $(ls "$PSRC" | wc -l))"
echo "manifest: $MANIFEST"
